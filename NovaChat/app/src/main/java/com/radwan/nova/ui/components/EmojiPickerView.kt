@Composable
fun EmojiPickerView(
    onEmojiSelected: (String) -> Unit,
    onBackspace: () -> Unit,
    modifier: Modifier = Modifier
) {
    var selectedCategoryIndex by remember { mutableIntStateOf(0) }

    Column(
        modifier = modifier
            .fillMaxWidth()
            .background(Color(0xFF1E293B))
    ) {
        // شريط التصنيفات وزر الحذف
        Row(
            modifier = Modifier
                .fillMaxWidth()
                .background(Color(0xFF0F172A))
                .padding(horizontal = 4.dp, vertical = 2.dp),
            verticalAlignment = Alignment.CenterVertically
        ) {
            Row(
                modifier = Modifier
                    .weight(1f)
                    .horizontalScroll(rememberScrollState()),
                horizontalArrangement = Arrangement.spacedBy(2.dp)
            ) {
                EMOJI_CATEGORIES.forEachIndexed { index, (catIcon, _) ->
                    val isSelected = index == selectedCategoryIndex
                    IconButton(
                        onClick = { selectedCategoryIndex = index },
                        modifier = Modifier
                            .size(38.dp)
                            .then(
                                if (isSelected) Modifier.background(
                                    Color(0xFF334155),
                                    shape = MaterialTheme.shapes.small
                                ) else Modifier
                            )
                    ) {
                        Text(text = catIcon, fontSize = 18.sp)
                    }
                }
            }

            // زر الحذف
            IconButton(
                onClick = onBackspace,
                modifier = Modifier.size(38.dp)
            ) {
                Text(text = "⌫", fontSize = 20.sp, color = Color(0xFF94A3B8))
            }
        }

        HorizontalDivider(color = Color(0xFF334155), thickness = 0.5.dp)

        // شبكة الإيموجيات
        val currentEmojis = EMOJI_CATEGORIES[selectedCategoryIndex].second
        LazyVerticalGrid(
            columns = GridCells.Adaptive(minSize = 42.dp),
            modifier = Modifier
                .fillMaxSize()
                .padding(horizontal = 6.dp, vertical = 4.dp),
            contentPadding = PaddingValues(bottom = 8.dp)
        ) {
            items(currentEmojis) { emoji ->
                Box(
                    modifier = Modifier
                        .size(44.dp)
                        .clickable { onEmojiSelected(emoji) },
                    contentAlignment = Alignment.Center
                ) {
                    Text(text = emoji, fontSize = 24.sp)
                }
            }
        }
    }
}
